-- Отклонённые заявки не удаляются автоматически.
--
-- Автоочистка (shift_requests_cleanup, ежедневный cron) сносила всё, чему день
-- смены старше недели, вместе с отказами. Порог совпадал с окном списка
-- намеренно — «удаляем ровно то, чего человек и так не видит». Но отказ живёт
-- дольше своей недели: по нему разбирают, кто и как часто просится опоздать, а
-- с 29.08 у сотрудника ещё и лимит в одну заявку на неделю, и история отказов —
-- единственное, по чему видно, как он расходуется.
--
-- Одобренные и отозванные чистятся как раньше: одобренная заявка уже переписала
-- график и живёт в нём, отозванная не дошла до руководства.
--
-- Ручную чистку в админке (cleanup_old_data, раздел «Заявки», минимум три
-- месяца) не трогаем: это осознанное действие владельца с предпросмотром
-- количества, а не фоновое удаление.
create or replace function public.shift_requests_cleanup(p_days integer default 7)
returns integer language plpgsql security definer set search_path = public as $$
declare
  v_n integer;
begin
  delete from shift_requests
   where date < (public.business_today() - p_days)
     and status <> 'rejected';
  get diagnostics v_n = row_count;

  -- В журнал пишем только когда реально удалили: иначе ежедневная запись «0»
  -- вытеснит из него настоящие действия (в админ-панели видно последние 50).
  if v_n > 0 then
    insert into activity_log (user_id, user_name, action, details)
    values (null, 'Система', 'Очистка заявок',
            format('удалено %s заявок старше %s дней', v_n, p_days));
  end if;

  return v_n;
end $$;
