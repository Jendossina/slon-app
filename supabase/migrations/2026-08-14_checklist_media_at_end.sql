-- Фото к чек-листу целиком, а не к каждому пункту.
--
-- Как было: у каждого пункта своя кнопка «прикрепить». Чтобы отчитаться за
-- смену, человек открывал модалку столько раз, сколько пунктов, и каждый раз
-- ждал загрузку. На практике фотографируют не пункт, а зал: один общий снимок
-- закрывает сразу несколько строк списка.
--
-- Как стало: один блок в конце чек-листа, куда кладут сразу несколько фото.
--
-- Старые фото по пунктам остаются в items_media и по-прежнему открываются на
-- своих строках — стирать историю смен нельзя, по ней разбирают спорные случаи.
-- Новые уходят в media. Колонка отдельная, а не ключ внутри items_media,
-- потому что это разные вещи: там «фото пункта 7», здесь «фото смены».
alter table public.checklist_logs add column if not exists media jsonb;

comment on column public.checklist_logs.media is
  'Фото/видео ко всему чек-листу: массив {url,type}. Пофайловая привязка к пунктам — в items_media (историческая).';
