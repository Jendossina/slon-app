-- Отделы у стандарта значат «кого касается», а не «кто видит» (владелец,
-- 01.11.2026: «менеджеры будут видеть все стандарты всех цехов, но у них
-- есть и для них стандарты»).
--
-- Менеджеры (role = manager) и так видят все статьи — это в политике
-- kb_articles_read. Но в редакторе это не было сказано, и к каждому
-- стандарту зала ставили галочку «Менеджеры», чтобы они его видели. Из-за
-- этого весь зал попадал и во вкладку «Менеджеры».
--
-- Разбор уже проставленного:
--   все пять цехов сразу — это стандарт для всех: отделы снимаем (вкладка «Общие»);
--   «Менеджеры» вместе с другими цехами — галочка ради видимости: убираем.
-- Статьи, где «Менеджеры» — единственный отдел, не трогаем: это и есть
-- стандарты для менеджеров.

update public.kb_articles
   set depts = null, updated_at = now()
 where depts @> array['Официанты','Бармены','Кальянные мастера','Повара','Менеджеры'];

update public.kb_articles
   set depts = array_remove(depts, 'Менеджеры'), updated_at = now()
 where 'Менеджеры' = any(depts) and cardinality(depts) > 1;
