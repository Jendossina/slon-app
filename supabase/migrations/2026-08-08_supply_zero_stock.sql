-- Хозчасть Чехова: обнулить остатки, позиции оставить (решение владельца).
--
-- Часом раньше миграция 2026-08-08_supply_chekhov_stock.sql завела те же
-- позиции с начальными остатками. Остатки решено убрать: список расходников
-- нужен, а количества будут внесены приходом, когда их пересчитают.
--
-- Убираем именно партии, а не проставляем им qty_left = 0. Партия с нулевым
-- остатком означает «пришло 4, израсходовали 4», и в отчёте расхода это
-- выглядело бы как списание, которого не было: supply_moves пуст, никто ничего
-- не брал. Партий, кроме заведённых той миграцией, в базе нет.
--
-- Условие qty_in = qty_left — страховка на случай повторного запуска позже:
-- если к этому моменту с партии уже что-то списали, она не тронется, и история
-- расхода не осиротеет.

delete from public.supply_batches
 where note = 'Начальный остаток'
   and unit_price = 0
   and qty_in = qty_left;
