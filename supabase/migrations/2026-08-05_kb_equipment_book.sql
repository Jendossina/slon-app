■ ЧТО ЭТО И ГДЕ СТОИТ
Модель, где находится, к какому филиалу относится.

■ КТО ОТВЕЧАЕТ
Должность, а не имя: имена меняются, регламент — нет.

■ ПЕРЕД ВКЛЮЧЕНИЕМ
Что проверить, пока техника выключена.

■ КАК РАБОТАТЬ
Порядок действий на смене, по шагам.

■ ЧЕГО НЕЛЬЗЯ
Список запретов. Пишем прямо и коротко: то, что ломает технику или опасно для человека.

■ ЧИСТКА
Ежедневно: что и когда (в открытие, в закрытие).
Раз в неделю: что и в какой день.
Чем чистить и чем нельзя.

■ ПРИЗНАКИ НЕИСПРАВНОСТИ
По каким признакам понятно, что пора звать мастера, а не «работать дальше».

■ ЧТО ДЕЛАТЬ ПРИ ПОЛОМКЕ
1. Выключить и обесточить.
2. Сообщить управляющему.
3. Кому звонить (контакт — в разделе «Справочник»).
Работать на неисправном оборудовании нельзя.

