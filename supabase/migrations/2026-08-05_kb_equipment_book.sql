$$Здесь лежит регламент работы с оборудованием: по одной статье на каждую единицу техники.

Статью может открыть любой сотрудник — с телефона, прямо на смене. Найти можно поиском по Базе знаний или спросить у Помощника: он отвечает по этим же статьям.

Править статьи могут админ и управляющий.

■ ФОРМАТ КАРТОЧКИ
Чтобы карточки читались одинаково, пишем каждую по одному шаблону. Скопируйте его целиком в новую статью и заполните.

Название статьи — как оборудование называют на смене, а не по паспорту.
Например: «Кофемашина», а не «Rocket Appartamento R58».

