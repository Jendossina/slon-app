--
-- Что сделано:
--   1. dishware_items получает category (зона: Зал / Бар / Кухня) и photo_url —
--      фото позиции грузится из приложения, в списке показывается миниатюра.
--   2. Уникальный индекс (filial, lower(name)) — одна позиция на филиал,
--      он же делает seed идемпотентным через on conflict do nothing.
--   3. Заливка 61 позиции: посуда, стекло и приборы. Мебель, техника зала,
--      кухонное оборудование и туалетные принадлежности из листа не берутся.
--
-- Количества сложены по одинаковым наименованиям со всех листов инвентаря
-- (напр. вилка столовая 77 + 47 = 124). Себестоимость не проставлена — в
-- инвентарном листе цен нет, поэтому cost = 0, и убыток в отчёте боя будет
-- нулевым, пока цены не проставят руками («Изменить» в карточке позиции).
--
-- Повторный запуск безопасен: колонки и индекс — if not exists, вставка —
-- do nothing, поэтому уже отредактированные остатки и цены не перетираются.

