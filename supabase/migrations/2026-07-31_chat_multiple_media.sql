-- Несколько фото в одном сообщении общего чата.
--
-- Было: media_url + media_type — ровно один файл на сообщение.
-- Стало: media jsonb — массив [{url, type}, ...], как items_media у чек-листов.
--
-- Старые колонки НЕ трогаем и продолжаем заполнять первым файлом: на телефонах
-- какое-то время живёт закешированная прошлая версия приложения, и она умеет
-- читать только media_url. Так старый клиент покажет хотя бы первое фото
-- вместо пустого пузыря.
--
-- Старые сообщения (media = null) читаются по-прежнему из media_url — клиент
-- приводит одно к другому функцией chatMediaList().

alter table public.team_chat add column if not exists media jsonb;

comment on column public.team_chat.media is
  'массив [{url,type}] — все вложения сообщения; media_url/media_type дублируют первое для старых клиентов';
