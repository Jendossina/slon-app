-- Хозчасть филиала Чехов: список расходников с фактическими остатками.
--
-- Четыре позиции уже были заведены черновыми именами и без единой партии
-- («Азелит», «Губки», «дельфины», «тряпки»), поэтому остаток по ним показывался
-- нулевой. Их не дублируем, а переименовываем под нормальные названия и
-- дописываем остаток — иначе в списке оказалось бы два «Азелита».
--
-- Остаток в хозчасти складывается из партий (supply_batches), у позиции своего
-- поля с количеством нет. Поэтому «остаток 2 штуки» = партия на 2 штуки.
-- Цен закупки нет, поэтому unit_price = 0: стоимость склада по этим партиям
-- будет нулевой, пока цену не проставят приходом из приложения. Побочный
-- эффект списания по FIFO: бесплатная партия спишется первой, и только потом
-- пойдут те, что заведут с ценой.
--
-- «Порошок», «Освежитель воздуха» и «Хлорка таблетки» заводятся без количества
-- (решение владельца) — позиция в списке есть, остаток нулевой.
--
-- Повторный запуск безопасен: переименование ищет старое имя и второй раз его
-- не находит, вставки идут через not exists, партии заводятся только позициям,
-- у которых партий ещё нет.

-- ===== 1. Черновые имена → нормальные =====
update public.supply_items set name = 'Губки для посуды', unit = 'упак'
 where filial = 'chekhov' and lower(name) = 'губки';

update public.supply_items set name = 'Дельфины тряпки', unit = 'упак'
 where filial = 'chekhov' and lower(name) = 'дельфины';

update public.supply_items set name = 'Цветные тряпки', unit = 'упак'
 where filial = 'chekhov' and lower(name) = 'тряпки';

update public.supply_items set unit = 'шт'
 where filial = 'chekhov' and lower(name) = 'азелит';

-- ===== 2. Недостающие позиции =====
insert into public.supply_items (name, unit, filial)
select v.name, v.unit, 'chekhov'
  from (values
    ('Доместос',                  'шт'),
    ('Хлорка',                    'шт'),
    ('Жидкое мыло',               'шт'),
    ('Порошок',                   'шт'),
    ('Освежитель воздуха',        'шт'),
    ('Хлорка таблетки',           'шт'),
    ('Мистер мускул',             'шт'),
    ('Вафельные полотенца',       'шт'),
    ('Половые тряпки',            'шт'),
    ('Резиновые перчатки жёлтые', 'пара'),
    ('Гарбич пакеты',             'шт'),
    ('Гарбич маленькие',          'шт')
  ) as v(name, unit)
 where not exists (
   select 1 from public.supply_items i
    where i.filial = 'chekhov' and lower(i.name) = lower(v.name)
 );

-- ===== 3. Начальные остатки =====
-- Только тем позициям, у которых партий ещё нет: иначе повторный запуск задвоил
-- бы остаток, а списанное вернулось бы на склад.
insert into public.supply_batches (item_id, qty_in, qty_left, unit_price, filial, note)
select i.id, v.qty, v.qty, 0, 'chekhov', 'Начальный остаток'
  from (values
    ('Доместос',                   2),
    ('Хлорка',                     1),
    ('Жидкое мыло',                3),
    ('Губки для посуды',           2),
    ('Дельфины тряпки',            4),
    ('Цветные тряпки',             4),
    ('Азелит',                     4),
    ('Мистер мускул',              4),
    ('Вафельные полотенца',        3),
    ('Половые тряпки',             4),
    ('Резиновые перчатки жёлтые',  3),
    ('Гарбич пакеты',             10),
    ('Гарбич маленькие',           4)
  ) as v(name, qty)
  join public.supply_items i
    on i.filial = 'chekhov' and lower(i.name) = lower(v.name)
 where not exists (select 1 from public.supply_batches b where b.item_id = i.id);
