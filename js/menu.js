// Плоский список «блюдо + раздел» для поиска
function kitchenMenuFlat() {
  const out = [];
  KITCHEN_MENU.forEach(g => g.items.forEach(name => out.push({ name, section: g.section })));
  return out;
}

// Поиск без учёта регистра, «ё» и лишних пробелов: официант ищет «елочка» —
// находит «Ёлочка», ищет по куску слова в середине названия — тоже находит.
function menuNormalize(s) {
  return (s || '').toLowerCase().replace(/ё/g, 'е').replace(/\s+/g, ' ').trim();
}
function searchKitchenMenu(query) {
  const q = menuNormalize(query);
  const all = kitchenMenuFlat();
  if(!q) return all;
  return all.filter(d => menuNormalize(d.name).includes(q) || menuNormalize(d.section).includes(q));
}
